"""Maintain the shipped Beast protocol engine over the isolated Asio backend."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def relocate(text: str) -> str:
    text = text.replace("boost/beast/", "webcpp/beast/detail/backend/")
    text = text.replace("boost/asio/", "webcpp/asio/detail/backend/")
    text = re.sub(r"namespace boost\s*\{\s*namespace beast\s*\{",
                  "namespace webcpp { namespace beast_backend {", text)
    text = re.sub(r"namespace boost\s*\{\s*namespace asio\s*\{",
                  "namespace webcpp { namespace asio_backend {", text)
    text = text.replace("boost::beast", "webcpp::beast_backend")
    text = text.replace("boost::asio", "webcpp::asio_backend")
    text = re.sub(r"(?<![\w:])beast::", "::webcpp::beast_backend::", text)
    text = re.sub(r"(?<![\w:])asio::", "::webcpp::asio_backend::", text)
    text = re.sub(r"(?<![\w:])system::", "::boost::system::", text)
    text = text.replace("BOOST_ASIO_", "WEBCPP_ASIO_BACKEND_")
    return text.replace("BOOST_BEAST_", "WEBCPP_BEAST_BACKEND_")


def outputs(boost: Path) -> dict[str, str]:
    pin = json.loads((ROOT / "upstream/pin.json").read_text())
    result: dict[str, str] = {}
    banner = "// Generated by upstream/sync.py; edit its pinned inputs, not this file.\n"
    for name, expected in pin["headers"].items():
        data = (boost / "boost/beast" / name).read_bytes()
        if digest(data) != expected:
            raise ValueError("upstream header differs from pinned Beast 1.92: " + name)
        text = data.decode()
        if name == "core/detail/config.hpp":
            old = ("namespace boost {\nnamespace asio\n{\n} // asio\nnamespace beast {\n"
                   "namespace net = boost::asio;\n} // beast\n} // boost")
            if old not in text:
                raise ValueError("Beast namespace prelude differs from pinned source")
            text = text.replace(old, "namespace boost {}\nnamespace webcpp::asio_backend {}\n"
                                "namespace webcpp::beast_backend {\n"
                                "using namespace ::boost;\n"
                                "namespace net = ::webcpp::asio_backend;\n}")
        if name == "core/detail/variant.hpp":
            # Chunk serialization allocates while constructing a variant alternative.
            # Propagate that failure instead of terminating inside unconditional noexcept.
            old = "    emplace(Args&&... args) noexcept\n"
            if text.count(old) != 1:
                raise ValueError("Beast variant emplace differs from pinned source")
            text = text.replace(old, "    emplace(Args&&... args) noexcept(\n"
                                "        std::is_nothrow_constructible<\n"
                                "            mp11::mp_at_c<variant, I - 1>, Args...>::value)\n")
            text = text.replace("#include <boost/mp11/algorithm.hpp>\n",
                                "#include <boost/mp11/algorithm.hpp>\n#include <type_traits>\n")
        result["include/webcpp/beast/detail/backend/" + name] = banner + relocate(text)
        if (not name.endswith(".hpp") or any(p in ("detail", "impl") for p in Path(name).parts)
                or name in pin["owned_facades"]):
            continue
        guard = "WEBCPP_BEAST_FORWARD_" + re.sub(r"[^A-Z0-9]", "_", name.upper())
        if name.startswith("websocket/"):
            include = ("#if WEBCPP_BEAST_HAS_SOCKET_BACKEND\n"
                       f"#include WEBCPP_BEAST_BACKEND_HEADER({name})\n"
                       "#endif\n#include <webcpp/beast/websocket.hpp>\n")
            if name == "websocket/ssl.hpp":
                include += "#include <webcpp/beast/ssl.hpp>\n"
        elif name == "core/tcp_stream.hpp":
            include = "#include <webcpp/beast/tcp_stream.hpp>\n"
        else:
            include = f"#include WEBCPP_BEAST_BACKEND_HEADER({name})\n"
        result["include/webcpp/beast/" + name] = (
            banner + f"#ifndef {guard}\n#define {guard}\n"
            "#include <webcpp/beast/config.hpp>\n" + include + "#endif\n")
    result["upstream/generated.json"] = json.dumps(
        {name: digest(data.encode()) for name, data in sorted(result.items())}, indent=2) + "\n"
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--boost-include", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = outputs(args.boost_include)
        for name, data in generated.items():
            path = ROOT / name
            if args.check:
                if not path.is_file() or path.read_text() != data:
                    raise ValueError("generated file is stale: " + name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(data)
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + "\n")
    print(f"Beast shipped engine: {len(generated)} files {'verified' if args.check else 'written'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
